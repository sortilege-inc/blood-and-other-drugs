"""Ids a corpus rebuild moved, old -> new, for engine/state.js renameIds (PLAYBOOK §4; L5R5e I8).

    python3 build/renamed_ids.py <old rev> [<old rev> ...]     (run from the repo root)

For every entity id that an earlier data build (a git revision of data/) carries and the current
data/ does not, the new id is the entity of the SAME NAME in the SAME BOOK that the current data
carries and the old build did not — when there is exactly one. An id with no such successor (a
fragment the rebuild removed: a heading split mid-word, a "Lore" label that is now text) is left
out, and counted. Writes system/vtm5e/renamed-ids.js (window.VttIdRenames); a stored campaign that
names an old id is rewritten on read, so its members, scene casts and notes keep their references.
"""
import json, os, re, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def entities(data_dir):
    """{id: (book, name)} from a data/ directory, read with node (the files are JS)."""
    js = r"""
const fs = require('fs'), path = require('path');
const window = {}; const dir = process.argv[1];
for (const f of fs.readdirSync(dir)) { if (f.endsWith('.js')) { try { eval(fs.readFileSync(path.join(dir, f), 'utf8')); } catch (e) {} } }
const T = window.VTM5E || {}; const out = {};
for (const [bid, b] of Object.entries(T.books || {})) for (const [id, e] of Object.entries(b.entities || {})) out[id] = [bid, e && e.name];
for (const [id, e] of Object.entries(T.entities || {})) if (!out[id]) out[id] = [e && e.book, e && e.name];
process.stdout.write(JSON.stringify(out));
"""
    r = subprocess.run(['node', '-e', js, data_dir], capture_output=True, text=True, check=True)
    return json.loads(r.stdout)


def main(revs):
    new = entities(os.path.join(ROOT, 'data'))
    renames, dropped = {}, 0
    for rev in revs:
        with tempfile.TemporaryDirectory() as tmp:
            subprocess.run(f'git -C {ROOT} archive {rev} data | tar -x -C {tmp}', shell=True, check=True)
            old = entities(os.path.join(tmp, 'data'))
        born = {i for i in new if i not in old}
        by_key = {}
        for i in born:
            by_key.setdefault(tuple(new[i]), []).append(i)
        for i, key in old.items():
            if i in new or i in renames:
                continue
            cands = by_key.get(tuple(key), [])
            if len(cands) == 1:
                renames[i] = cands[0]
            else:
                dropped += 1
        print(f'{rev}: {sum(1 for i in old if i not in new)} ids gone', file=sys.stderr)
    body = ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v)}' for k, v in sorted(renames.items()))
    path = os.path.join(ROOT, 'system', 'vtm5e', 'renamed-ids.js')
    with open(path, 'w') as fh:
        fh.write('// Generated by build/renamed_ids.py — ids the corpus rebuild moved, old -> new (engine/state.js\n'
                 '// renameIds). Never edited by hand.\n'
                 f'window.VttIdRenames = Object.assign(window.VttIdRenames || {{}}, {{\n{body}\n}});\n')
    print(f'renamed_ids: {len(renames)} ids renamed, {dropped} gone with no single successor -> system/vtm5e/renamed-ids.js')


if __name__ == '__main__':
    main(sys.argv[1:])
